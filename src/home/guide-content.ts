export function findChapter(id: string): GuideChapter | null {
    for (const s of GUIDE_SECTIONS) {
        const hit = s.chapters.find((c) => c.id === id);
        if (hit) return hit;
    }
    return null;
}

export function firstChapterId(): string {
    for (const s of GUIDE_SECTIONS) {
        if (s.chapters.length) return s.chapters[0].id;
    }
    return '';
}
